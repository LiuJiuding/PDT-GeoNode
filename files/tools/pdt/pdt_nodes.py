#!/usr/bin/env python3
"""PDT custom geometry-node manager.

Single source of truth for the custom nodes added on top of upstream Blender.

    python tools/pdt_nodes.py list [--json]
    python tools/pdt_nodes.py new <NodeId> "<Label>" [--description "..."]
    python tools/pdt_nodes.py sync      # regenerate CMake + add-menu blocks
    python tools/pdt_nodes.py check     # manifest <-> sources <-> build/UI wiring

Everything is driven by
``blender/source/blender/nodes/geometry/nodes/custom/nodes.json``.
The generated regions are delimited by ``PDT CUSTOM ... BEGIN/END`` markers so
that upstream merges/rebase conflicts stay trivial.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

# Repo root = <repo>/tools/pdt/pdt_nodes.py -> parents[2]. Override with PDT_REPO.
REPO = Path(os.environ.get("PDT_REPO") or Path(__file__).resolve().parents[2])
CUSTOM_DIR = REPO / "source/blender/nodes/geometry/nodes/custom"
MANIFEST = CUSTOM_DIR / "nodes.json"
CMAKE_FILE = REPO / "source/blender/nodes/geometry/CMakeLists.txt"
MENU_FILE = REPO / "scripts/startup/bl_ui/node_add_menu_geometry.py"
RNA_FILE = REPO / "source/blender/makesrna/intern/rna_nodetree.cc"
TEMPLATE = Path(__file__).resolve().parent / "templates/node_geo_custom.cc.in"

CMAKE_BEGIN = "# --- PDT CUSTOM NODES BEGIN (generated by tools/pdt_nodes.py) ---"
CMAKE_END = "# --- PDT CUSTOM NODES END ---"
RNA_BEGIN = "  /* --- PDT CUSTOM NODES BEGIN (generated by tools/pdt_nodes.py) --- */"
RNA_END = "  /* --- PDT CUSTOM NODES END --- */"
RNA_ANCHOR = '  define("GeometryNode", "GeometryNodeXPBDSolver");'
MENU_BEGIN = "# --- PDT CUSTOM NODES BEGIN (generated by tools/pdt_nodes.py) ---"
MENU_END = "# --- PDT CUSTOM NODES END ---"
DICT_BEGIN = "    # --- PDT CUSTOM MENUS BEGIN (generated by tools/pdt_nodes.py) ---"
DICT_END = "    # --- PDT CUSTOM MENUS END ---"
ROOT_BEGIN = "        # --- PDT CUSTOM ROOT BEGIN (generated by tools/pdt_nodes.py) ---"
ROOT_END = "        # --- PDT CUSTOM ROOT END ---"

ID_RE = re.compile(r"^GeometryNode[A-Z][A-Za-z0-9]*$")


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def load_manifest() -> dict:
    if not MANIFEST.exists():
        return {"comment": "", "nodes": []}
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def save_manifest(data: dict) -> None:
    MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def replace_region(
    path: Path, begin: str, end: str, body: list[str], anchor: str | None, after: bool = False
) -> bool:
    """Replace the marked region in `path`. Returns True when the file changed."""
    text = path.read_text(encoding="utf-8")
    block = "\n".join([begin, *body, end])
    if begin in text and end in text:
        new_text = re.sub(
            re.escape(begin) + r".*?" + re.escape(end), lambda _m: block, text, flags=re.DOTALL
        )
    else:
        if anchor is None:
            die(f"no marker and no anchor given for {path}")
        if anchor not in text:
            die(f"anchor {anchor!r} not found in {path}")
        replacement = anchor + "\n" + block if after else block + "\n" + anchor
        new_text = text.replace(anchor, replacement, 1)
    if new_text != text:
        path.write_text(new_text, encoding="utf-8")
        return True
    return False


def sync_cmake(nodes: list[dict]) -> bool:
    body = ["list(APPEND INC nodes/custom)", "list(APPEND SRC"]
    for node in nodes:
        body.append(f"  {node['source']}")
    body.append(")")
    return replace_region(CMAKE_FILE, CMAKE_BEGIN, CMAKE_END, body, "add_node_discovery(")


def rna_define_line(node: dict) -> str:
    """The `define(...)` line for one node.

    A node whose storage needs RNA of its own (an item list that drives dynamic sockets, e.g. the
    wrangle's channels) names the function that defines those properties in the manifest
    (`"rna_def": "rna_def_geo_pdt_wrangle"`); everything else needs only the bare struct."""
    rna_def = node.get("rna_def")
    if rna_def:
        return f'  define("GeometryNode", "{node["id"]}", {rna_def});'
    return f'  define("GeometryNode", "{node["id"]}");'


def sync_rna(nodes: list[dict]) -> bool:
    """Every node type needs an RNA struct: without it `node_type_base` asserts
    (and, in release builds, dereferences a null StructRNA and crashes)."""
    body = [rna_define_line(node) for node in nodes]
    return replace_region(RNA_FILE, RNA_BEGIN, RNA_END, body, RNA_ANCHOR, after=True)


def sync_menu(nodes: list[dict]) -> list[Path]:
    changed: list[Path] = []
    menu_nodes = [n for n in nodes if n.get("menu", True)]
    categories: dict[str, list[dict]] = {}
    for node in menu_nodes:
        categories.setdefault(node.get("category", "PDT"), []).append(node)

    classes: list[str] = []
    dict_entries: list[str] = []
    root_entries: list[str] = []
    for category, cat_nodes in categories.items():
        cls = "NODE_MT_gn_" + re.sub(r"\W+", "_", category).lower() + "_base"
        ident = "NODE_MT_geometry_node_" + re.sub(r"\W+", "_", category).upper()
        classes += [f"class {cls}(node_add_menu.NodeMenu):", f'    bl_label = "{category}"', "",
                    "    def draw(self, _context):", "        layout = self.layout"]
        for node in cat_nodes:
            classes.append(f'        self.node_operator(layout, "{node["id"]}")')
        classes += ["", "        self.draw_assets_for_catalog(layout, self.bl_label)", "", ""]
        dict_entries.append(f'    "{ident}": {cls},')
        root_entries.append(f'        self.draw_menu(layout, "{category}")')

    if replace_region(MENU_FILE, MENU_BEGIN, MENU_END, classes, "add_menus = {"):
        changed.append(MENU_FILE)
    if replace_region(MENU_FILE, DICT_BEGIN, DICT_END, dict_entries, None):
        changed.append(MENU_FILE)
    if replace_region(MENU_FILE, ROOT_BEGIN, ROOT_END, root_entries, None):
        changed.append(MENU_FILE)
    return changed


def cmd_list(args: argparse.Namespace) -> int:
    nodes = load_manifest()["nodes"]
    if args.json:
        print(json.dumps(nodes, ensure_ascii=False, indent=2))
        return 0
    if not nodes:
        print("(no custom nodes yet)")
        return 0
    width = max(len(n["id"]) for n in nodes)
    for node in nodes:
        print(f"{node['id']:<{width}}  {node['label']:<24} {node['source']}")
    return 0


def cmd_new(args: argparse.Namespace) -> int:
    node_id = args.node_id
    if not ID_RE.match(node_id):
        die("node id must look like GeometryNodeSomething")
    data = load_manifest()
    if any(n["id"] == node_id for n in data["nodes"]):
        die(f"{node_id} already exists in the manifest")

    stem = camel_to_snake(node_id.removeprefix("GeometryNode"))
    # The file prefix already says "pdt", so drop a redundant leading "pdt_".
    stem = re.sub(r"^pdt_", "", stem) or stem
    file_stem = f"node_geo_pdt_{stem}.cc"
    namespace = f"node_geo_pdt_{stem}_cc"
    target = CUSTOM_DIR / file_stem
    if target.exists():
        die(f"{target} already exists")

    text = TEMPLATE.read_text(encoding="utf-8")
    text = (
        text.replace("{{ID}}", node_id)
        .replace("{{LABEL}}", args.label)
        .replace("{{NAMESPACE}}", namespace)
        .replace("{{DESCRIPTION}}", args.description)
    )
    target.write_text(text, encoding="utf-8")

    data["nodes"].append(
        {
            "id": node_id,
            "label": args.label,
            "category": args.category,
            "source": f"nodes/custom/{file_stem}",
            "namespace": namespace,
            "menu": True,
            "eval_node": False,
        }
    )
    save_manifest(data)
    cmd_sync(argparse.Namespace())

    print(f"created {target.relative_to(REPO)}")
    print("next:")
    print(f"  python tools/{Path(__file__).resolve().parent.name}/pdt_nodes.py sync   # if you edit nodes.json by hand")
    print("  . tools\\pdt\\build_dev.ps1 -Target install -Reconfigure   # reconfigure + compile + link")
    print("  . tools\\pdt\\run_tests.ps1                                # Python API smoke test")
    return 0


def camel_to_snake(name: str) -> str:
    """GeometryNodePDTSmokeCheck -> pdt_smoke_check (acronyms stay together)."""
    first = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    second = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", first)
    return re.sub(r"_+", "_", second).lower().strip("_")


def cmd_sync(_args: argparse.Namespace) -> int:
    nodes = load_manifest()["nodes"]
    cmake_changed = sync_cmake(nodes)
    rna_changed = sync_rna(nodes)
    menu_changed = sync_menu(nodes)
    print(f"cmake {'updated' if cmake_changed else 'unchanged'}: {CMAKE_FILE.name}")
    print(f"rna   {'updated' if rna_changed else 'unchanged'}: {RNA_FILE.name}")
    print(f"add-menu {'updated' if menu_changed else 'unchanged'}: {MENU_FILE.name}")
    if cmake_changed:
        print("NOTE: CMakeLists changed -> the build script must reconfigure (build_dev.ps1 -Reconfigure)")
    return 0


def cmd_check(_args: argparse.Namespace) -> int:
    nodes = load_manifest()["nodes"]
    problems: list[str] = []
    cmake_text = CMAKE_FILE.read_text(encoding="utf-8")
    menu_text = MENU_FILE.read_text(encoding="utf-8")
    rna_text = RNA_FILE.read_text(encoding="utf-8")

    for node in nodes:
        source = CUSTOM_DIR / Path(node["source"]).name
        if not source.exists():
            problems.append(f"{node['id']}: missing source {source.relative_to(REPO)}")
            continue
        text = source.read_text(encoding="utf-8")
        if f'geo_node_type_base(&ntype, "{node["id"]}"_ustr)' not in text:
            problems.append(f"{node['id']}: source does not register that node id")
        registrations = re.findall(r"NOD_REGISTER_NODE\(\w+\)", text)
        if "NOD_REGISTER_NODE(node_register)" not in text:
            problems.append(f"{node['id']}: missing the NOD_REGISTER_NODE(node_register) macro")
        elif len(registrations) != 1:
            problems.append(
                f"{node['id']}: found {len(registrations)} NOD_REGISTER_NODE(...) matches - "
                "a mention inside a comment would register a bogus global symbol"
            )
        if node["source"] not in cmake_text:
            problems.append(f"{node['id']}: not listed in {CMAKE_FILE.name} (run sync)")
        if rna_define_line(node) not in rna_text:
            problems.append(
                f"{node['id']}: missing RNA definition in {RNA_FILE.name} "
                "(run sync - without it Blender crashes while registering the node)"
            )
        if node.get("menu", True) and f'"{node["id"]}"' not in menu_text:
            problems.append(f"{node['id']}: not present in the Python add-menu (run sync)")

    ids = [n["id"] for n in nodes]
    if len(ids) != len(set(ids)):
        problems.append("duplicate node ids in the manifest")

    for problem in problems:
        print(f"FAIL {problem}")
    print(f"checked {len(nodes)} custom node(s): {len(problems)} problem(s)")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list", help="list custom nodes")
    p_list.add_argument("--json", action="store_true")
    p_list.set_defaults(func=cmd_list)

    p_new = sub.add_parser("new", help="scaffold a new custom node")
    p_new.add_argument("node_id")
    p_new.add_argument("label")
    p_new.add_argument("--description", default="")
    p_new.add_argument("--category", default="PDT")
    p_new.set_defaults(func=cmd_new)

    sub.add_parser("sync", help="regenerate CMake + add-menu blocks").set_defaults(func=cmd_sync)
    sub.add_parser("check", help="verify manifest wiring").set_defaults(func=cmd_check)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
